      <div><p class="eyebrow">Comprehension</p><h3>${percent >= 75 ? "Good result." : percent >= 50 ? "Partly there." : "Worth another listen."}</h3><p>${percent === 100 ? "Every detail landed. Try a fresh room or a harder level." : "Read the explanations, then replay the section that held the answer."}</p></div>
