export async function renderListening(root, { signal }) {
  const controller = new AbortController();
  const abort = () => controller.abort();
  if (signal) signal.addEventListener("abort", abort, { once: true });
  const state = { exercise: null, source: "studio", notice: "" };
  let player = null;
  let playerRate = 0.92;
  let currentSpeed = 0.92;
  let questionResults = null;

  root.innerHTML = `<div class="page-loading"><div class="skeleton-line skeleton-line--eyebrow"></div><div class="skeleton-line skeleton-line--heading"></div><div class="skeleton-line skeleton-line--medium"></div><div class="skeleton-card" style="margin-top:28px;min-height:340px"></div></div>`;

  async function loadExercise() {
    try {
      const data = await api.get("/api/listening/exercise", { signal: controller.signal });
      state.exercise = data.exercise;
      state.source = "studio";
      paint();
    } catch (error) {
      if (error.name === "AbortError") return;
      root.innerHTML = `<div class="fatal-view"><div class="fatal-view__mark">${icon("alert", 24)}</div><p class="eyebrow">The room is silent</p><h1>We couldn’t open the listening room.</h1><p>${escapeHTML(error.message)}</p><button class="btn btn--primary" data-retry-listening>Try again ${icon("rotate", 16)}</button></div>`;
      root.querySelector("[data-retry-listening]")?.addEventListener("click", () => renderListening(root, { signal }));
    }
  }

  function paint() {
    if (player) player.destroy();
    questionResults = null;
    root.innerHTML = pageHTML(state.exercise, state.source, state);
    setupPlayer();
    updateListeningState("idle", 0, 0);
  }

  function setupPlayer() {
    player = new SpeechPlayer(state.exercise.script, {
      accent: state.exercise.accent || "British",
      rate: playerRate,
      onState: (event) => {
        const card = root.querySelector("#listening-player");
        if (!card) return;
        card.classList.toggle("is-playing", event.state === "playing");
        updateListeningState(event.state, event.index, event.total);
      },
      onProgress: (event) => {
        const bar = root.querySelector("#listening-progress-bar");
        if (bar) bar.style.width = `${event.percent}%`;
      }
    });
    currentSpeed = playerRate;
    root.querySelectorAll("[data-listening-speed]").forEach((button) => {
      button.classList.toggle("is-active", Number(button.dataset.listeningSpeed) === playerRate);
    });
  }

  function updateListeningState(status, index, total) {
    const button = root.querySelector("#listening-play");
    const label = root.querySelector("#listening-state");
    if (!button || !label) return;
    if (status === "playing") {
      button.innerHTML = icon("pause", 26);
      button.setAttribute("aria-label", "Pause listening");
      label.textContent = "Playing — follow the argument";
    } else if (status === "paused") {
      button.innerHTML = icon("play", 28);
      button.setAttribute("aria-label", "Resume listening");
      label.textContent = "Paused — the room will wait";
    } else if (status === "ended") {
      button.innerHTML = icon("rotate", 25);
      button.setAttribute("aria-label", "Replay listening");
      label.textContent = "Finished — replay or answer the questions";
    } else if (status === "error") {
      button.innerHTML = icon("play", 28);
      label.textContent = "The browser’s voice could not play. Try another browser.";
    } else {
      button.innerHTML = icon("play", 28);
      button.setAttribute("aria-label", "Play listening");
      label.textContent = supportsSpeech() ? "Press play when you’re ready" : "Playback is unavailable in this browser";
    }
    const count = root.querySelector("#listening-count");
    if (count && total) count.textContent = `${index || 0} / ${total} parts`;
  }

  function openGenerator() {
    openModal({
      title: "A new listening room.",
      subtitle: "Pick a topic and a voice. Daymark will write a short talk and four questions for it.",
      size: "lg",
      content: generatorContent(),
      onMount: ({ panel, close }) => {
        const form = panel.querySelector("#listening-generator");
        const submit = panel.querySelector("#listening-generate-submit");
        panel.querySelectorAll("[data-listen-topic]").forEach((chip) => {
          chip.addEventListener("click", () => {
            panel.querySelector("#listen-topic").value = chip.dataset.listenTopic;
            panel.querySelectorAll("[data-listen-topic]").forEach((each) => each.classList.toggle("is-active", each === chip));
          });
        });
        form.addEventListener("submit", async (event) => {
          event.preventDefault();
          const payload = {
            level: form.querySelector("#listen-level").value,
            accent: form.querySelector("#listen-accent").value,
            topic: form.querySelector("#listen-topic").value.trim() || "Everyday life"
          };
          setButtonLoading(submit, true, "Writing the talk…");
          try {
            const data = await api.post("/api/listening/generate", payload);
            close();
            if (player) player.destroy();
            state.exercise = data.exercise;
            state.source = data.source;
            state.notice = data.fallbackReason || "";
            playerRate = currentSpeed || 0.92;
            paint();
            toast(data.source === "gemini" ? "A fresh listening room is ready." : "A built-in listening room is ready.", { type: "success" });
          } catch (error) {
            setButtonLoading(submit, false);
            const box = document.createElement("div");
            box.className = "form-error";
            box.innerHTML = `${icon("alert", 16)}<span>${escapeHTML(error.message)}</span>`;
            submit.before(box);
          }
        });
      }
    });
  }

  async function submitAnswers() {
    const form = root.querySelector("#listening-form");
    if (!form) return;
    const answers = [];
    let complete = true;
    state.exercise.questions.forEach((_, index) => {
      const selected = form.querySelector(`input[name="listen-q${index}"]:checked`);
      if (!selected) complete = false;
      answers.push(selected ? Number(selected.value) : null);
    });
    if (!complete) {
      toast("Answer every question before checking.", { type: "error" });
      return;
    }
    const button = root.querySelector("#submit-listening");
    setButtonLoading(button, true, "Checking…");
    try {
      const data = await api.post("/api/listening/attempt", { exerciseId: state.exercise.id, answers });
      questionResults = data;
      const body = root.querySelector("#listening-question-body");
      if (body) body.innerHTML = resultsHTML(data);
      const transcript = root.querySelector("#listening-transcript");
      if (transcript) transcript.open = true;
      refreshSummary();
      const feedback = root.querySelector("#listening-feedback");
      if (feedback) feedback.scrollIntoView({ behavior: "smooth", block: "start" });
    } catch (error) {
      setButtonLoading(button, false);
      toast(error.message, { type: "error" });
    }
  }

  const clickHandler = (event) => {
    if (event.target.closest("[data-new-listening]")) {
      if (player) player.pause();
      openGenerator();
      return;
    }
    if (event.target.closest("#listening-play")) {
      if (!player) return;
      player.toggle();
      return;
    }
    if (event.target.closest("#listening-replay")) {
      if (player) player.replay();
      return;
    }
    const speed = event.target.closest("[data-listening-speed]");
    if (speed) {
      const rate = Number(speed.dataset.listeningSpeed);
      currentSpeed = rate;
      playerRate = rate;
      root.querySelectorAll("[data-listening-speed]").forEach((button) => button.classList.toggle("is-active", button === speed));
      if (player) player.setRate(rate);
      return;
    }
    if (event.target.closest("[data-retry-listening]")) {
      const section = root.querySelector("#listening-questions");
      if (section) {
        section.outerHTML = questionsHTML(state.exercise);
        root.querySelector("#listening-questions")?.scrollIntoView({ behavior: "smooth", block: "start" });
      }
      return;
    }
    const option = event.target.closest(".choice");
    if (option) {
      // Change events handle selection; this is only for focus visuals.
      return;
    }
  };

  root.addEventListener("click", clickHandler, { signal: controller.signal });
  root.addEventListener(
    "change",
    (event) => {
      if (event.target.matches('input[type="radio"][name^="listen-q"]')) {
        const question = event.target.closest(".listening-question");
        question?.querySelectorAll(".choice").forEach((choice) => {
          choice.classList.toggle("is-selected", Boolean(choice.querySelector("input:checked")));
        });
      }
    },
    { signal: controller.signal }
  );

  root.addEventListener(
    "submit",
    (event) => {
      if (event.target.id === "listening-form") {
        event.preventDefault();
        submitAnswers();
      }
    },
    { signal: controller.signal }
  );

  await loadExercise();

  return () => {
    if (player) player.destroy();
    controller.abort();
    if (signal) signal.removeEventListener("abort", abort);
  };
}

